#!/usr/bin/env python3
"""
Тестирование очистки экранированных символов
"""

def clean_escaped_text(text: str) -> str:
    """Очищает текст от экранированных символов JSON"""
    if not text:
        return ""
    
    # Убираем экранированные символы JSON
    cleaned = text.replace('\\"', '"')  # Убираем экранированные кавычки
    cleaned = cleaned.replace('\\n', ' ')  # Убираем экранированные переносы строк 
    cleaned = cleaned.replace('\\t', ' ')  # Убираем экранированные табуляции
    cleaned = cleaned.replace('\\\\', '\\')  # Убираем двойные обратные слеши
    
    return cleaned.strip()


def test_escape_cleaning():
    """Тестирует очистку различных видов экранирования"""
    
    test_cases = [
        # Тест 1: Экранированные кавычки (как в проблеме)
        'К сожалению, информация, предоставленная в источниках, не содержит ответа на вопрос \\"Кто круче - Гарри Поттер или Кристиано Роналду?\\".',
        
        # Тест 2: Экранированные переносы строк
        'Чат-бот EORA\\nумеет отвечать\\nна вопросы.',
        
        # Тест 3: Экранированные табуляции
        'Проект\\tA\\tи\\tпроект\\tB',
        
        # Тест 4: Двойные слеши
        'Путь к файлу: C:\\\\Users\\\\Admin',
        
        # Тест 5: Смешанные экранирования
        'Ответ: \\"Да, это возможно\\". \\nПодробности в документации.',
    ]
    
    print("🧪 ТЕСТИРОВАНИЕ ОЧИСТКИ ЭКРАНИРОВАННЫХ СИМВОЛОВ")
    print("=" * 80)
    
    for i, test_case in enumerate(test_cases, 1):
        print(f"\n📝 Тест {i}:")
        print(f"До:   '{test_case}'")
        cleaned = clean_escaped_text(test_case)
        print(f"После: '{cleaned}'")
        print("-" * 40)
    
    print("\n🎯 ИТОГ: Все тесты выполнены!")


if __name__ == "__main__":
    test_escape_cleaning()
